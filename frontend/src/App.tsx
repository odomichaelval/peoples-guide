import { useState } from "react";
import "./App.css";

export default function App() {
  const [situation, setSituation] = useState("");
  const [reply, setReply] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  async function getSupport() {
    if (loading || situation.trim().length < 10) return;

    setLoading(true);
    setError("");
    setReply("");

    try {
      const response = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ message: situation.trim() }),
      });

      if (!response.ok) {
        throw new Error(
          "Unable to get a response. Check that the backend and local model are running."
        );
      }

      const data = await response.json();

      if (typeof data.reply !== "string" || !data.reply.trim()) {
        throw new Error("The model returned an empty response. Please try again.");
      }

      setReply(data.reply);
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Something went wrong."
      );
    } finally {
      setLoading(false);
    }
  }

  function reset() {
    setSituation("");
    setReply("");
    setError("");
  }

  return (
    <main className="page">
      <header className="header">
        <a className="brand" href="/">People’s Guide</a>
        <span className="badge">Sheffield prototype</span>
      </header>

      <section className="hero">
        <span className="eyebrow">
          SUPPORT STARTS WITH UNDERSTANDING
        </span>
        <h1>
          Find your next step.<br />
          Get the support you need.
        </h1>
        <p>
          The right support. The right information. One place.
          Tell us what is happening, and we’ll help you explore
          relevant public services.
        </p>
      </section>

      <section className="card" aria-labelledby="form-title">
        <h2 id="form-title">What’s happening in your life?</h2>
        <p className="muted">
          You can tell us about work, housing, money or caring responsibilities.
        </p>

        <label htmlFor="situation">Describe your situation</label>
        <textarea
          id="situation"
          value={situation}
          onChange={(event) => setSituation(event.target.value)}
          maxLength={4000}
          rows={6}
          disabled={loading}
          placeholder="For example: I live in Sheffield, recently lost my job and am struggling with rent."
        />

        <p className="privacy">
          Please leave out names, exact addresses, bank details and
          National Insurance numbers. Your text is sent to our backend
          on the team’s DGX Spark for local model processing.
        </p>

        <div className="actions">
          <button
            className="primary"
            onClick={getSupport}
            disabled={loading || situation.trim().length < 10}
          >
            {loading ? "Reviewing your situation…" : "Explore support"}
          </button>

          <button
            className="example"
            disabled={loading}
            onClick={() => setSituation(
              "I live in Sheffield, recently lost my job and am struggling to pay rent and council tax."
            )}
          >
            Use an example
          </button>

          <button
            className="example"
            onClick={reset}
            disabled={loading}
          >
            Clear
          </button>
        </div>

        <p className="notice">
          Early prototype: responses are generated by AI and are not yet
          checked against official service documents.
        </p>

        {error && <p className="error" role="alert">{error}</p>}

        <div aria-live="polite" aria-busy={loading}>
          {loading && (
            <p className="muted">
              Waiting for the local model. This may take a little time.
            </p>
          )}

          {reply && (
            <section className="result" aria-labelledby="result-title">
              <h2 id="result-title">Your response</h2>
              <div className="answer">{reply}</div>
            </section>
          )}
        </div>
      </section>

      <footer>
        Guidance helps you explore options. Official services determine eligibility.
      </footer>
    </main>
  );
}